/**
 * Things people say about a meal, with what they mean. Hindi (Devanagari), Hinglish and English; typed and
 * spoken style; one dish to a whole day. The truth here is written from the person's side ("2 roti" means two
 * rotis), never copied from what the engine returned, so a failing line is either a bug or a decision to make.
 *
 * `f` names a set of acceptable catalogue foods (FOODS below): "dal" accepts any plain dal dish, "roti" accepts
 * Roti (Chapati) and Phulka. A food that must not be offered as a sure match because the word is genuinely open
 * ("paneer", "biscuit") is marked `amb`.
 */

import type { MealSlotId } from "../dishes";

export interface Want {
  /** Key of FOODS. */
  f: string;
  /** The count of the unit that should be priced (match.quantity). */
  q?: number;
  /** The household unit the row is counted in (contained in match.unit); "g" / "ml" for a typed weight. */
  u?: string;
  /** A typed weight in grams (match.grams must equal it). */
  g?: number;
  /** The word is open: the engine may pre-select a likely food, but must not call it a sure match. */
  amb?: boolean;
}

export interface Utt {
  say: string;
  want: Want[];
  slot?: MealSlotId | null;
  day?: 0 | -1 | -2 | null;
  /** A deliberate, documented gap: the line is still run and reported, but a miss does not fail the gate. */
  known?: string;
}

