/**
 * Regenerates src/lib/vision/meal-vocab.ts: the dish names the meal-photo reader is asked to prefer, taken from the
 * everyday ("core") cooked foods of the bundled catalogue (see buildMealVocabulary in src/lib/vision/meal-map.ts).
 *
 *   node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON scripts/food/meal-vocab.mjs           show whether the file is current
 *   node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON scripts/food/meal-vocab.mjs --write   rewrite it
 *
 * The prompt of the meal reader is built synchronously on the server, where the 2.6 MB catalogue is loaded
 * asynchronously, so the list is a checked-in file; `npm run ai:eval` fails when a name in it no longer finds a food.
 */
import fs from "node:fs";
import path from "node:path";
import { src, root } from "../soie-node-hooks.mjs";

const { loadEvalCatalogue } = await import(src("lib/food/eval/catalogue-node.ts"));
const { buildMealVocabulary } = await import(src("lib/vision/meal-map.ts"));

const names = buildMealVocabulary(loadEvalCatalogue().foods);
const file = path.join(root, "src", "lib", "vision", "meal-vocab.ts");
const body = `/**
 * GENERATED by scripts/food/meal-vocab.mjs from the everyday (core) cooked foods of src/data/food-catalogue.json:
 * the dish names the meal-photo reader is asked to prefer. Do not edit by hand; run the script after the
 * catalogue is rebuilt. Pure data, safe for the browser and the server.
 */
export const MEAL_VOCABULARY: readonly string[] = [
${names.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
];
`;

const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
if (process.argv.includes("--write")) {
  fs.writeFileSync(file, body);
  console.log(`wrote ${names.length} names to ${path.relative(root, file)}`);
} else if (current === body) {
  console.log(`${names.length} names: src/lib/vision/meal-vocab.ts is current`);
} else {
  console.log(`src/lib/vision/meal-vocab.ts is out of date (${names.length} names in the catalogue); run with --write`);
  process.exitCode = 1;
}
